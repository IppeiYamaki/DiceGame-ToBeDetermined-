/// <summary>
/// ダイスの役（コンボ）成立条件のタイプ
/// 3個のダイスの出目がどのような条件を満たせば役が成立するかを定義します
/// 
/// 各条件タイプの説明:
/// 
/// - ExactNumbers:
///   指定した数字構成と完全一致（順不同）
///   例: ピンゾロ（1,1,1）、シゴロ（4,5,6）、ヒフミ（1,2,3）
/// 
/// - AllSame:
///   3つすべて同じ数字
///   例: ゾロ目全般（2,2,2 / 3,3,3 / 4,4,4 / 5,5,5 / 6,6,6）
///   ※ AllowedNumbers で許可する数字を指定できます（例: 2～6のみ）
/// 
/// - AllInAllowedSet:
///   指定した数字セット内のみで構成（重複OK）
///   例: 偶数のみ（2,4,6の中から3つ）、奇数のみ（1,3,5の中から3つ）
/// 
/// - SameNumberCount:
///   同じ数字が指定数以上ある
///   例: ワンペア（同じ数字が2個以上）
/// </summary>
public enum DiceRoleConditionType
{
    /// <summary>
    /// 指定した数字構成と完全一致（順不同）
    /// 例: ピンゾロ（1,1,1）、シゴロ（4,5,6）、ヒフミ（1,2,3）
    /// </summary>
    ExactNumbers,

    /// <summary>
    /// 3つすべて同じ数字
    /// 例: ゾロ目全般（2,2,2 / 3,3,3 / 4,4,4 / 5,5,5 / 6,6,6）
    /// </summary>
    AllSame,

    /// <summary>
    /// 指定した数字セット内のみで構成（重複OK）
    /// 例: 偶数のみ（2,4,6の中から3つ）、奇数のみ（1,3,5の中から3つ）
    /// </summary>
    AllInAllowedSet,

    /// <summary>
    /// 同じ数字が指定数以上ある
    /// 例: ワンペア（同じ数字が2個以上）
    /// </summary>
    SameNumberCount
}
